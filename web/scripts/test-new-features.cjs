'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync(path.resolve(__dirname,'../index.html'),'utf8');
function launch(snapshot={}){
  return new JSDOM(html,{url:'https://example.test/kanri/',runScripts:'dangerously',pretendToBeVisual:true,beforeParse(win){
    win.matchMedia=()=>({matches:false,addListener(){},removeListener(){}});
    for(const [key,value] of Object.entries(snapshot))win.localStorage.setItem(key,value);
  }});
}
function element(doc,selector){const el=doc.querySelector(selector);assert.ok(el,'Missing '+selector);return el;}
function click(doc,selector){element(doc,selector).click();}
function tasks(win){return JSON.parse(win.localStorage.getItem('kanri_v1_tasks')||'[]');}
let dom=launch(),doc=dom.window.document;
click(doc,'[data-quick-folder="work"]');
click(doc,'#childQuickAdd');
element(doc,'#folderName').value='車種A';
click(doc,'#folderSave');
let folders=JSON.parse(dom.window.localStorage.getItem('kanri_v2_folders'));
const carA=folders.find(f=>f.name==='車種A');
assert.equal(carA.parentId,'work');
assert.ok(carA.id.startsWith('folder-'),'vehicle name is now an ordinary child tree');
click(doc,'#addButton');
element(doc,'#fTitle').value='車種Aの設計確認';
click(doc,'#saveTask');
assert.equal(tasks(dom.window)[0].folderId,carA.id);
assert.equal(doc.querySelectorAll('.task-card').length,1);
click(doc,'[data-quick-folder="work"]');
click(doc,'#childQuickAdd');
element(doc,'#folderName').value='車種B';
click(doc,'#folderSave');
folders=JSON.parse(dom.window.localStorage.getItem('kanri_v2_folders'));
const carB=folders.find(f=>f.name==='車種B');
assert.equal(carB.parentId,'work');
assert.equal(doc.querySelectorAll('.task-card').length,0,'car B excludes car A tasks');
click(doc,'[data-tab="calendar"]');
click(doc,'[data-mode="month"]');
const chosenDate=element(doc,'.month-grid .day.sel').dataset.caldate;
click(doc,'#addEventTop');
element(doc,'#eventTitle').value='車種Bの定例会議';
element(doc,'#eventDate').value=chosenDate;
element(doc,'#eventTime').value='15:30';
element(doc,'#eventDuration').value='120';
element(doc,'#eventFolder').value=carB.id;
click(doc,'#eventSave');
const meeting=tasks(dom.window).find(t=>t.event);
assert.ok(meeting,'meeting saved as calendar event');
assert.equal(meeting.scheduled,chosenDate+'T15:30');
assert.equal(meeting.duration,120);
assert.equal(meeting.folderId,carB.id);
assert.ok(element(doc,'.agenda-list').textContent.includes('車種Bの定例会議'));
click(doc,'[data-mode="gantt"]');
assert.equal(doc.querySelectorAll('.gantt-names .gantt-label-row').length,20,'exactly 20 label rows');
assert.equal(doc.querySelectorAll('.gantt-scroll-table .gantt-task-row').length,20,'exactly 20 Gantt rows');
assert.equal(element(doc,'.gantt-excel').style.getPropertyValue('--display-rows'),'20');
assert.ok(element(doc,'.gantt-names').textContent.includes('車種Bの定例会議'));
click(doc,'[data-tab="puzzle"]');
const meetingTile=element(doc,'[data-remove="'+meeting.id+'"]');
meetingTile.click();
assert.ok(element(doc,'#eventTitle'),'meeting chip opens schedule editor, not an unschedule action');
click(doc,'#eventCancel');
click(doc,'#clearDay');
assert.equal(tasks(dom.window).find(t=>t.id===meeting.id).scheduled,chosenDate+'T15:30','puzzle clear must never unschedule meetings');
click(doc,'[data-tab="board"]');
assert.equal(doc.querySelectorAll('.task-card').length,0,'calendar-only events are not focus tasks');
click(doc,'[data-quick-folder="work"]');
assert.equal(doc.querySelectorAll('.task-card').length,1,'work aggregates vehicle tasks');
const saved=Object.fromEntries(Object.keys(dom.window.localStorage).map(k=>[k,dom.window.localStorage.getItem(k)]));
dom.window.close();
dom=launch(saved);doc=dom.window.document;
assert.ok(tasks(dom.window).find(t=>t.event&&t.title==='車種Bの定例会議'),'meeting survives reload');
assert.equal(JSON.parse(dom.window.localStorage.getItem('kanri_v2_folders')).filter(f=>f.parentId==='work').length,2,'generic child folders survive reload');
// Arbitrary-depth nesting and one-tap deletion of a formerly vehicle-named folder.
click(doc,'[data-quick-folder="work"]');
click(doc,'#folderMenuButton');
click(doc,'[data-folder-open="'+carB.id+'"]');
click(doc,'#folderAdd');
element(doc,'#folderName').value='車種以外：試作品の工程';
click(doc,'#folderSave');
const nested=JSON.parse(dom.window.localStorage.getItem('kanri_v2_folders')).find(f=>f.name==='車種以外：試作品の工程');
assert.ok(nested&&nested.parentId===carB.id,'new child tree can be created below existing child');
click(doc,'#childQuickAdd');
element(doc,'#folderName').value='工程の詳細';
click(doc,'#folderSave');
const thirdLevel=JSON.parse(dom.window.localStorage.getItem('kanri_v2_folders')).find(f=>f.name==='工程の詳細');
assert.equal(thirdLevel.parentId,nested.id,'three-level tree can be created');
click(doc,'[data-quick-folder="work"]');
click(doc,'#folderMenuButton');
assert.equal(doc.querySelectorAll('.folder-delete-visible').length,2,'each non-root child has direct delete button');
click(doc,'.folder-delete-visible[data-folder-trash="'+carB.id+'"]');
assert.ok(element(doc,'#confirmDelete'),'folder delete asks for confirmation');
click(doc,'#confirmDelete');
let afterDelete=JSON.parse(dom.window.localStorage.getItem('kanri_v2_folders'));
assert.ok(!afterDelete.some(f=>f.id===carB.id),'vehicle-named child can be deleted');
assert.equal(afterDelete.find(f=>f.id===nested.id).parentId,'work','deleted tree children are moved to parent');
assert.equal(afterDelete.find(f=>f.id===thirdLevel.id).parentId,nested.id,'deeper children retain nested relationships');
assert.equal(tasks(dom.window).find(t=>t.id===meeting.id).folderId,'work','linked calendar event is moved with its deleted folder');
dom.window.close();
// One-tap completion from FOCUS and Gantt, with a recoverable 7-day trash.
dom=launch();doc=dom.window.document;
click(doc,'#addButton');element(doc,'#fTitle').value='完了と復元の検証タスク';click(doc,'#saveTask');
let sample=tasks(dom.window).find(t=>t.title==='完了と復元の検証タスク');
assert.ok(sample,'test task created');
click(doc,'[data-done="'+sample.id+'"]');
let finished=tasks(dom.window).find(t=>t.id===sample.id);
assert.equal(finished.done,true,'one click completes a FOCUS task');
assert.ok(!Number.isNaN(Date.parse(finished.completedAt)),'completion date is persisted');
assert.equal(doc.querySelectorAll('.task-card').length,0,'completed tasks leave FOCUS');
click(doc,'[data-tab="settings"]');click(doc,'#openTrash');
assert.ok(element(doc,'.trash-item').textContent.includes(sample.title),'completed task is in trash');
click(doc,'[data-restore="'+sample.id+'"]');
assert.equal(tasks(dom.window).find(t=>t.id===sample.id).done,false,'trash restore makes task active again');
click(doc,'[data-tab="calendar"]');click(doc,'[data-mode="gantt"]');
assert.equal(doc.querySelectorAll('.gantt-names .gantt-label-row').length,20,'complete buttons do not alter Gantt row count');
click(doc,'[data-gantt-done="'+sample.id+'"]');
assert.equal(tasks(dom.window).find(t=>t.id===sample.id).done,true,'one-tap Gantt completion');
assert.ok(!doc.querySelector('[data-gantt-done="'+sample.id+'"]'),'completed task disappears from active Gantt');
click(doc,'#trashCalendar');click(doc,'[data-restore="'+sample.id+'"]');
assert.equal(tasks(dom.window).find(t=>t.id===sample.id).done,false,'Gantt-completed task is recoverable');
const completedAt=new Date().toISOString();
const snapshot=Object.fromEntries(Object.keys(dom.window.localStorage).map(k=>[k,dom.window.localStorage.getItem(k)]));
const stale={...sample,id:'expired-task',title:'8日前に完了',done:true,completedAt:new Date(Date.now()-8*86400000).toISOString()};
const recent={...sample,id:'recent-task',title:'6日前に完了',done:true,completedAt:new Date(Date.now()-6*86400000).toISOString()};
snapshot.kanri_v1_tasks=JSON.stringify([stale,recent]);
dom.window.close();dom=launch(snapshot);doc=dom.window.document;
assert.ok(!tasks(dom.window).some(t=>t.id===stale.id),'completed item older than 7 days is automatically purged on launch');
assert.ok(tasks(dom.window).some(t=>t.id===recent.id),'completion newer than 7 days is retained');
click(doc,'[data-tab="settings"]');click(doc,'#openTrash');
assert.equal(doc.querySelectorAll('.trash-item').length,1,'trash displays retained item only');
click(doc,'[data-remove-forever="'+recent.id+'"]');
click(doc,'#confirmDelete');
assert.equal(tasks(dom.window).length,0,'explicit permanent deletion removes retained item');
dom.window.close();
console.log('PASS one-tap FOCUS/Gantt completion, seven-day retention, recovery and permanent deletion');
// Render every task, even when more than 20; verify vertical name/date scroll synchronization.
dom=launch();doc=dom.window.document;
const matrixData=Array.from({length:26},(_,i)=>({...sample,id:'matrix-'+i,title:'ガント縦スクロール '+i,done:false,completedAt:null,pin:false,rank:null}));
dom.window.localStorage.setItem('kanri_v1_tasks',JSON.stringify(matrixData));
dom.window.close();
dom=launch({kanri_v1_tasks:JSON.stringify(matrixData)});doc=dom.window.document;
click(doc,'[data-tab="calendar"]');click(doc,'[data-mode="gantt"]');
assert.equal(doc.querySelectorAll('.gantt-names .gantt-label-row').length,26,'all 26 task labels render');
assert.equal(doc.querySelectorAll('.gantt-scroll-table .gantt-task-row').length,26,'all 26 task calendar rows render');
assert.equal(element(doc,'.gantt-excel').style.getPropertyValue('--display-rows'),'20','viewport still scales to 20 rows');
const left=element(doc,'#ganttNameBody'),right=element(doc,'#ganttDayBody');
left.scrollTop=65;left.dispatchEvent(new dom.window.Event('scroll'));
assert.equal(right.scrollTop,65,'left scrolling synchronizes right dates');
right.scrollTop=120;right.dispatchEvent(new dom.window.Event('scroll'));
assert.equal(left.scrollTop,120,'right scrolling synchronizes left labels');
assert.ok(element(doc,'#ganttDayBody').textContent.includes('') && element(doc,'#ganttNameBody').textContent.includes('ガント縦スクロール 25'));
dom.window.close();
console.log('PASS 26-row vertical Gantt scrolling and synchronized headers, arbitrary nested trees and visible deletion');
console.log('PASS 20-row Gantt, meeting schedule CRUD, vehicle folder navigation and persistence');
