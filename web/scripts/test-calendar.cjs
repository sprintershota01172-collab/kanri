const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync(require('node:path').join(__dirname,'..','index.html'),'utf8');
const dom=new JSDOM(html,{
  url:'https://kanri.example.test/',pretendToBeVisual:true,runScripts:'dangerously',
  beforeParse(win){win.matchMedia=()=>({matches:false,addListener(){},removeListener(){}})}
});
const doc=dom.window.document;
const get=s=>{const el=doc.querySelector(s);assert.ok(el,'Missing '+s);return el};
function click(s){get(s).click()}
function tasks(){return JSON.parse(dom.window.localStorage.getItem('kanri_v1_tasks')||'[]')}
click('#addButton');
assert.ok(get('#fDueButton'),'due date is a calendar picker, not text input');
assert.equal(get('#fDue').type,'hidden','due date cannot trigger text keyboard');
click('#fDueButton');
assert.equal(doc.querySelectorAll('[data-due-date]').length,42,'42 calendar choices');
click('#dateNext');
assert.equal(doc.querySelectorAll('[data-due-date]').length,42,'calendar month navigation');
click('#datePrev');
const date='2026-10-20';
for(let i=0;i<36&&!doc.querySelector('[data-due-date="'+date+'"]');i++)click('#dateNext');
assert.ok(get('[data-due-date="'+date+'"]'));
click('[data-due-date="'+date+'"]');
assert.equal(get('#fDue').value,date,'picked day saved inside form');
assert.equal(get('#fDueText').textContent,date,'chosen due date visible in button');
get('#fTitle').value='週次報告';
click('#saveTask');
assert.equal(tasks().length,1);
assert.equal(tasks()[0].due,date,'calendar selection persists to task');
click('[data-tab="calendar"]');
assert.ok(get('[data-mode="gantt"]').classList.contains('selected'),'Gantt is the default PLAN mode');
assert.ok(get('.gantt-excel'),'Gantt displays before selecting the monthly calendar');
click('[data-mode="month"]');
for(let i=0;i<20&&!doc.querySelector('[data-caldate="'+date+'"]');i++)click('#nextDate');
assert.ok(get('[data-caldate="'+date+'"]'),'task date is visible on calendar');
assert.equal(doc.querySelectorAll('[data-caladd]').length,0,'calendar has no add controls');
assert.ok(get('[data-caldate="'+date+'"] .day-dots .dot'),'monthly dot marks registered FOCUS task');
click('[data-caldate="'+date+'"]');
assert.ok(get('.agenda-list').textContent.includes('週次報告'),'registered task visible in daily agenda');
assert.equal(tasks().length,1,'PLAN navigation never creates tasks');
click('[data-mode="week"]');
const weekDay=get('[data-caldate="'+date+'"]');
assert.ok(weekDay.textContent.includes('1件'),'weekly compact card displays task count');
assert.equal(doc.querySelectorAll('.week-task-label').length,0,'compact week design restored');
assert.equal(doc.querySelectorAll('.week-day-add').length,0,'no plus in week view');
assert.ok(get('.agenda-list').textContent.includes('週次報告'),'week shows selected day task in agenda');
click('[data-tab="board"]');
click('#addButton');
get('#fTitle').value='新規打ち合わせ';
click('#fDueButton');
const other='2026-10-21';
for(let i=0;i<24&&!doc.querySelector('[data-due-date="'+other+'"]');i++)click('#dateNext');
click('[data-due-date="'+other+'"]');
click('#saveTask');
assert.equal(tasks().length,2,'second task is created only in FOCUS');
click('[data-tab="calendar"]');
click('[data-mode="month"]');
for(let i=0;i<20&&!doc.querySelector('[data-caldate="'+other+'"]');i++)click('#nextDate');
click('[data-caldate="'+other+'"]');
assert.ok(get('.agenda-list').textContent.includes('新規打ち合わせ'),'second FOCUS task appears automatically');
click('[data-mode="week"]');
assert.ok(get('.agenda-list').textContent.includes('新規打ち合わせ'),'second FOCUS task appears in week');
click('[data-tab="settings"]');
click('#rename');
assert.ok(get('[data-name]'),'settings text-input overlay opens');
assert.ok(html.includes('.modal-layer{position:fixed!important'),'mobile CSS fixes settings overlay to viewport');
assert.ok(doc.documentElement.style.getPropertyValue('--kanri-locked-height'),'fixed viewport captured before keyboard');
click('#namesOK');
assert.equal(dom.window.localStorage.getItem('kanri_v1_tasks')!==null,true,'existing data retained');
dom.window.close();
console.log('PASS due picker, read-only month/week, FOCUS-to-PLAN sync, fixed modal');
